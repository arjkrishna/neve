class _D(object):
    def __init__(self, v):
        self.value = v

    def getValueString(self):
        return str(self.value)


class _Obj(object):
    def __init__(self, typ, kw):
        self._typ = typ
        for k, v in kw.items():
            setattr(self, k, _D(v))

    def findData(self, k):
        return getattr(self, k, None)


class _Node(object):
    def __init__(self, path, log):
        self._path, self._log, self._items = path, log, []

    def addChild(self, name):
        c = _Node(self._path + "/" + name, self._log)
        setattr(self, name, c)
        self._items.append(c)
        self._log.append(("child", c._path))
        return c

    def addObject(self, typ, name=None, **kw):
        o = _Obj(typ, kw)
        if name:
            setattr(self, name, o)
        self._items.append(o)
        self._log.append(("obj", self._path, typ, name))
        return o


def cmd_replay(a):
    """Build the whole scene on a fake SOFA API and step the controller through every row (see the module doc)."""
    t0 = time.time()
    S = stub_sofa()
    cfg = S.load_cfg(a.cfg)
    cfg["tag"] = a.tag
    cfg["min_vol_ratio_abort"] = -1e9                   # the fake tets have no meaningful volume
    log = []
    root = _Node("", log)
    inp = S.load_inputs(cfg)
    ctx = S.build_scene(root, cfg, inp)
    # every body the controller solves or reads: the five DEFORMABLE ones (static obstacles included, as before) plus
    # ctx["deformable"]'s extras -- the elastic corpus of corpus_model "fem", whose topology post_init reads (review
    # LOW-6: stubbing S.DEFORMABLE alone raised AttributeError in post_init on every fem cfg)
    bodies = list(S.DEFORMABLE) + [b for b in ctx.get("deformable", []) if b not in S.DEFORMABLE]
    for b in bodies:
        nd = ctx["nodes"][b]
        nd.dofs.position = _D(ctx["X0"][b].tolist())
        nd.dofs.velocity = _D(np.zeros_like(ctx["X0"][b]).tolist())
        nd.topo.tetrahedra = _D([[0, 1, 2, 3]])
    root.gcs.currentNumConstraints = _D(300)
    root.gcs.currentError = _D(0.5)
    root.gcs.currentIterations = _D(40)
    root.gcs.constraintForces = _D([0.1])
    ctrl = S.HybridController(name="h", ctx=ctx, out_dir=None)
    S.post_init(ctx)
    summ = S.scene_summary(ctx)
    sched = ctx["sched"]
    n_max = min(int(cfg["max_steps"]), len(sched) + 5)
    while not ctrl.done and ctrl.k < n_max:
        r = sched[min(ctrl.k, len(sched) - 1)]
        Tc = np.asarray(r["T_corpus"], float)
        for b in bodies:                                # the cervix (and an elastic corpus) carried by the row's pose
            X0 = ctx["X0"][b]
            X = X0 @ Tc[:3, :3].T + Tc[:3, 3] if b in ("cervix", "corpus") else X0.copy()
            ctx["nodes"][b].dofs.position.value = X.tolist()
        ctrl._begin()
        ctrl._end()
    rows = ctrl.rows
    # depth engagement: each node engages at the first step whose row carries tip_s >= canal_s, never before
    cs = ctx.get("canal_s")
    eng = ctrl.eng_step
    lag = []
    if cs is not None:
        for i, s_i in enumerate(cs):
            first = next((k for k, r in enumerate(sched) if r["phase"] not in ("B", "P") and r.get("tip_s") is not None
                          and float(r["tip_s"]) >= float(s_i)), None)
            lag.append(None if (first is None or eng[i] < 0) else int(eng[i]) - first)
    ph_of = lambda k: sched[min(k, len(sched) - 1)]["phase"]  # noqa: E731
    n_eng = [r.get("canal_tie", {}).get("n_engaged") for r in rows]
    out = dict(tag=a.tag, graph_ops=len(log), ovoid_nodes=[x for x in log if x[0] == "child" and "ovoid" in x[1]],
               ctx_ovoids_is_none=ctx.get("ovoids") is None, n_steps=len(rows), status=ctrl.status,
               phases_logged={p: sum(1 for r in rows if r["phase"] == p) for p in "BPVCLH"},
               scene_summary_phases=summ.get("phases"), extra_tandem_first=summ.get("tandem_first"),
               ovoid_body=summ.get("ovoid_body"), tie_set=summ.get("canal_tie_cfg"),
               ties=dict(n_nodes=int(len(eng)), n_engaged=int((eng >= 0).sum()),
                         engage_lag_steps=dict(min=min([x for x in lag if x is not None], default=None),
                                               max=max([x for x in lag if x is not None], default=None),
                                               n_never=int(sum(1 for x in lag if x is None))),
                         first_engaged_step=int(eng[eng >= 0].min()) if (eng >= 0).any() else None,
                         first_engaged_phase=ph_of(int(eng[eng >= 0].min())) if (eng >= 0).any() else None,
                         last_engaged_step=int(eng.max()) if (eng >= 0).any() else None,
                         plateau_from_step=next((k for k, n in enumerate(n_eng) if n == max(x for x in n_eng if x is not None)), None),
                         n_engaged_in_V=int(sum(1 for k in eng if k >= 0 and ph_of(int(k)) == "V"))),
               apex_lift_logged=dict(end_of_C=next((r["apex_lift_mm"] for r in reversed(rows) if r["phase"] == "C"), None),
                                     last=rows[-1].get("apex_lift_mm") if rows else None),
               tf_logged_last=rows[-1].get("tf") if rows else None, wall_s=round(time.time() - t0, 1))
    ok = (out["ctx_ovoids_is_none"] and not out["ovoid_nodes"] and out["ties"]["n_engaged"] == out["ties"]["n_nodes"]
          and out["ties"]["engage_lag_steps"]["max"] is not None and out["ties"]["engage_lag_steps"]["max"] <= 0
          and out["ties"]["engage_lag_steps"]["min"] >= 0 and all("tf" in r for r in rows if r["phase"] in "VCLH"))
