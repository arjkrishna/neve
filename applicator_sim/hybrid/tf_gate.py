    chk("apex lift through V and C (reported; expected <= 2 mm)", "max |lift| %.2f mm, end of C %.2f mm" % (
        apex_VC, per[iC[-1]]["apex_lift_mm"]), True, "report")
    # ---- reported
    rep = {}
    s_ios = geo.s_ios
