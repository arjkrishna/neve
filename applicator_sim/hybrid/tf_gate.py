        self.R_fin_json = np.asarray(df["R_rows"], float)
        self.x_fin = geom.ortho(self.R_fin_json[0], self.a_fin)
        self.split = geom.corpus_split(self.T_final, self.O)
        self.d_F = float(self.T["d_F"])
        self.d_fin = self.L_iu - self.d_F
