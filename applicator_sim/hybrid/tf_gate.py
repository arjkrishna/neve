    s["run"] = dict(tag=a.tag, cfg=a.cfg, unknown_cfg_keys=unknown, n_sched=len(sched),
                    phases={p: sum(1 for r in sched if r["phase"] == p) for p in "BPVCL"},
                    max_steps=cfg["max_steps"], rows_plus_settle=len(sched) + int(cfg["max_settle_steps"]),
                    record=dict(version=rec.get("version"), written=rec.get("written"), mode=rec.get("mode"),
                                lift_in_C=rec.get("lift_in_C"), fallback=rec.get("fallback")))
    s["accept"].append(dict(test="schedule fits max_steps (rows + max_settle_steps)",
                            measured="%d + %d = %d" % (len(sched), int(cfg["max_settle_steps"]), s["run"]["rows_plus_settle"]),
                            limit="<= %d" % int(cfg["max_steps"]), pass_=bool(s["run"]["rows_plus_settle"] <= int(cfg["max_steps"]))))
    s["accept"].append(dict(test="cfg keys known to scene_hybrid.CFG", measured=unknown, limit="none unknown",
                            pass_=not unknown))
