def _jsonable(o):
    if isinstance(o, dict):
        return {k: _jsonable(v) for k, v in o.items()}
    if isinstance(o, (list, tuple)):
        return [_jsonable(v) for v in o]
    if isinstance(o, np.ndarray):
        return _jsonable(o.tolist())
    if isinstance(o, (np.floating,)):
        return float(o)
    if isinstance(o, (np.integer,)):
        return int(o)
    if isinstance(o, np.bool_):
        return bool(o)
    return o


class Dist:
    """Unsigned distance to an OPEN triangle sheet (vtkImplicitPolyDataDistance magnitude; its sign is meaningless on
    an open sheet and is not used)."""

    def __init__(self, V, F):
        self.imp = vtk.vtkImplicitPolyDataDistance()
        self.imp.SetInput(TM.polydata(V, F))

    def __call__(self, P):
        P = np.atleast_2d(np.asarray(P, float))
        if not len(P):
            return np.zeros(0)
        arr = vtk.vtkDoubleArray()
        self.imp.FunctionValue(ns.numpy_to_vtk(np.ascontiguousarray(P), deep=1), arr)
        return np.abs(ns.vtk_to_numpy(arr))


def edge_midpoints(V, F):
    E = np.unique(np.sort(np.vstack([F[:, [0, 1]], F[:, [1, 2]], F[:, [2, 0]]]), axis=1), axis=0)
    return 0.5 * (V[E[:, 0]] + V[E[:, 1]])


