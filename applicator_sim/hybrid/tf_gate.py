def cmd_gate(a):
    t0 = time.time()
    S, cfg, inp, tgt, sched = load_run(a.cfg, a.tag)
    if cfg.get("insertion_path") != "tandem_first":
        raise SystemExit("gate: cfg insertion_path is %r, not 'tandem_first'" % cfg.get("insertion_path"))
    geo = Geo(cfg["vagina_wall_dir"], cfg["applicator_dir"], a.ref_run)
    rec = tgt["tandem_first"]
    prm = rec["params"]
    rows = [r for r in sched if r["phase"] in ("V", "C", "L")]
