    def portio(Tc):
        Tc = np.asarray(Tc, float)
        Xc = geo.cervix_V @ Tc[:3, :3].T + Tc[:3, 3]
        h = (Xc - top_c) @ top_t
        pc = geo.canal @ Tc[:3, :3].T + Tc[:3, 3]
        near = np.linalg.norm(Xc[:, None, :] - pc[None, :1, :], axis=2)[:, 0] <= 15.0
        return dict(lowest_mm=float(h.min()), lowest_within_15mm_of_os_mm=float(h[near].min()) if near.any() else None,
                    os_mm=float((pc[0] - top_c) @ top_t))
    rep["portio_to_wall_top_gap"] = dict(
        definition="axial coordinate along the wall's top-station tangent, relative to the rest wall's top station "
                   "(positive = above the wall top): the carried cervix's lowest surface point, the lowest within 15 mm "
                   "of the carried O_true, and O_true itself; cervix carried rigidly by the row's corpus transform",
        rest=portio(np.eye(4)), end_of_C=portio(rc["T_corpus"]))
    rep["apex_lift_estimate_mm"] = dict(V_max_abs=mx(iV, lambda e: abs(e["apex_lift_mm"])),
                                        C_max_abs=mx(iC, lambda e: abs(e["apex_lift_mm"])),
                                        end_of_C=per[iC[-1]]["apex_lift_mm"], end_of_L=per[iL[-1]]["apex_lift_mm"])
    # L: tandem and corpus as one body -- the tip and the flange in the corpus's rest frame must not move
    def in_corpus(r):
        Tc = np.asarray(r["T_corpus"], float)
        tip = np.asarray(r["F"], float) + geo.L_iu * geom.unit(r["tube_axis"])
        return np.r_[(tip - Tc[:3, 3]) @ Tc[:3, :3], (np.asarray(r["F"], float) - Tc[:3, 3]) @ Tc[:3, :3]]
    ref_ = in_corpus(rows[iC[-1]])
    rep["L_one_body_max_mm"] = max(float(np.abs(in_corpus(rows[i]) - ref_).max()) for i in iL)
    rep["canal_end_of_C"] = per[iC[-1]]["canal"]
    rep["canal_final"] = per[iL[-1]]["canal"]
    rep["lift_in_C"] = dict(L_C=L_C, norm_mm=lc, along_a_v_mm=float(L_C @ geo.a_w), z_mm=float(L_C[2]),
                            os_rise_along_a_v_in_C_mm=float(L_C @ geo.a_w))
    rep["steps"] = dict(V=len(iV), C=len(iC), L=len(iL),
                        max_corpus_mm_per_step=dict(C=mx(iC, lambda e: e["step"]["corpus_mm"]),
                                                    L=mx(iL, lambda e: e["step"]["corpus_mm"])),
                        max_device_point_mm_per_step=dict(V=mx(iV, lambda e: e["step"]["device_mm"]),
                                                          C=mx(iC, lambda e: e["step"]["device_mm"]),
                                                          L=mx(iL, lambda e: e["step"]["device_mm"])),
                        max_device_point_in_body_mm_per_step=dict(V=mx(iV, lambda e: e["step"]["device_in_body_mm"]),
                                                                  C=mx(iC, lambda e: e["step"]["device_in_body_mm"]),
                                                                  L=mx(iL, lambda e: e["step"]["device_in_body_mm"])),
                        max_axis_deg_per_step=dict(V=mx(iV, lambda e: e["step"]["axis_deg"]),
                                                   C=a_C, L=mx(iL, lambda e: e["step"]["axis_deg"])))
    rep["containment_closed_sheet_S0"] = dict(
        V_min=mn(iV, lambda e: e["contain"].get("min_clear_closed_sheet_mm")),
        C_min=mn(iC, lambda e: e["contain"].get("min_clear_closed_sheet_mm")),
        note="S0 (tf_metrics) clearance to the CLOSED lumen sheet, fan discs included")
    rep["V_tip_to_path_max_mm"] = mx(iV, lambda e: e.get("tip_to_path_mm"))
    summ = dict(accept=acc, pass_all=bool(all(x["pass_"] for x in acc)), reported=rep)
    return dict(summary=summ, per_row=per)


