"""scaleup_ia172_provenance: (re)write the scale-up section of thin_slice/ia172/PROVENANCE.md (scaleup_lane_ia172).

Idempotent: everything between the two marker lines below is regenerated from the case folders, so a rerun after each
new case keeps the file current. The pilot part of the file above the markers is never touched.
Rows: every scale-up case with ct.nii.gz + meta.json (fetched by scaleup_ia172_run.sh fetch = pilot_ia172_fetch.py);
skipped / rejected cases from derived/.../_logs_scaleup/rejected_<case> (pre-fetch arch check, by eye, fetch failure).
usage (neve-build-stagea): python3 scaleup_ia172_provenance.py
"""
import glob, json, os, re

SRC = "/repo/carotid_data/va_sources/thin_slice/ia172"
LOGD = "/repo/carotid_data/va_sources/derived/thin_slice/ia172/_logs_scaleup"
PRE = "/sp/v5_va/results/scaleup_ia172_prearch.json"
P = os.path.join(SRC, "PROVENANCE.md")
B, E = "<!-- scaleup_ia172 begin -->", "<!-- scaleup_ia172 end -->"

batch = [l.split()[0] for l in open(os.path.join(LOGD, "batch1_cases.txt")) if l.strip()] if os.path.exists(
    os.path.join(LOGD, "batch1_cases.txt")) else []
ext = [l.split()[0] for l in open(os.path.join(LOGD, "ext_cases.txt")) if l.strip()] if os.path.exists(
    os.path.join(LOGD, "ext_cases.txt")) else []
order = []
for c in batch + ext:
    c = c if c.startswith("ia172_") else "ia172_" + c
    if c not in order:
        order.append(c)
# also any scale-up case folder not in the lists (should not happen)
for pat in ("fetch_done_", "rejected_", "fetch_failed_"):
    for d in sorted(glob.glob(os.path.join(LOGD, pat + "*"))):
        c = os.path.basename(d)[len(pat):]
        if c not in order:
            order.append(c)


def x3(v):
    return " × ".join(f"{a:.3f}" if i < 2 else f"{a:.2f}" for i, a in enumerate(v))


rows, rej = [], []
pre = json.load(open(PRE)) if os.path.exists(PRE) else {}
for c in order:
    sid = c[len("ia172_"):]
    rf = os.path.join(LOGD, "rejected_" + c)
    ff = os.path.join(LOGD, "fetch_failed_" + c)
    m = os.path.join(SRC, c, "meta.json")
    if os.path.exists(rf) or os.path.exists(ff):
        why = open(rf if os.path.exists(rf) else ff).read().strip().replace("\n", " ")
        if why.startswith("prearch fail"):
            why = "pre-fetch arch check failed, not fetched: " + why[len("prearch fail"):].strip()
        rej.append(f"- **{c}** (CaseID {sid}): {why[:500]}")
        continue
    if not os.path.exists(m) or not os.path.exists(os.path.join(SRC, c, "ct.nii.gz")):
        continue
    j = json.load(open(m))
    st = j.get("aneurysm_status", "?")
    if st != "control":
        st = f"IA ({', '.join(j.get('aneurysms') or [])})"
    sc = j.get("scanner", {})
    vc = j.get("visual_check", {})
    verd = vc.get("verdict", "pending")
    flags = "; ".join(j.get("qc_auto_flags") or [])
    br = j.get("zip_byte_range") or ["?", "?"]
    shp = j.get("shape") or j.get("geometry", {}).get("shape") or []
    rows.append(f"| {c} | {sid} | {j.get('sex')}/{j.get('age_years')} | {st} | {sc.get('model', '')} {sc.get('software', '')} | "
                f"{x3(j['acquisition_voxel_mm'])} | {x3(j['grid_spacing_mm'])} | {'×'.join(str(s) for s in shp)} | "
                f"{j.get('z_extent_mm', 0):.0f} | {br[0]}–{br[1]} | {j.get('phase_auto', '')} | {flags or '–'} | {verd} |")

sec = [B, "", "## Scale-up cases (v5 donor scale-up, lane `scaleup_lane_ia172`, 2026-10-02)", "",
       "Fetched for the v5 VA donor scale-up in the order of `v5_va/results/pilot_next_cases.json` -> selection "
       "(de-duplicated there against the pilot and against same-demographics pairs). Same method as the pilot "
       "(`pilot_ia172_fetch.py` unchanged: zip byte-span range read, CRC-32 per member, `pilot_ia172_convert.py`), "
       "plus a **pre-fetch arch check** (`scaleup_ia172_prearch.py`: three range-read DICOM slices at the bottom, "
       "two aortic limbs required) and the same acceptance checks (arterial phase, subclavian origins and skull base "
       "in view by TotalSegmentator quick look, `scaleup_ia172_qc.py`; both VAs visible, by eye on `mip_neck.png`, "
       "`v5_va/results/scaleup_ia172_visual.json`). Licence and attribution as above (CC BY 4.0 images; anything "
       "through Arterial non-commercial). This section is regenerated by `v5_va/scaleup_ia172_provenance.py`.", "",
       "| case | CaseID | sex/age | status | scanner | acq. voxel (mm) | grid (mm) | shape | z (mm) | zip byte range | phase (auto) | auto flags | by eye |",
       "|---|---|---|---|---|---|---|---|---|---|---|---|---|"] + rows + [""]
if rej:
    sec += ["**Skipped / rejected (scale-up):**", ""] + rej + [""]
sec += [E]
txt = open(P).read()
if B in txt and E in txt:
    txt = txt[:txt.index(B)] + "\n".join(sec) + txt[txt.index(E) + len(E):]
else:
    txt = txt.rstrip("\n") + "\n\n" + "\n".join(sec) + "\n"
open(P, "w").write(txt)
print(f"PROVENANCE.md: {len(rows)} scale-up cases, {len(rej)} skipped")
